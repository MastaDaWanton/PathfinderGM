"""The shipped builds' sheets, made once here instead of at every start.

`rules/bestiary._people` made each of content/npc-builds/people.json's 272 builds into an
actor through the engine on every start, and that was 1.90 s of it: measured 2026-10-30, the
first `bestiary.imported()` went from 0.34-0.43 s before the builds shipped to 2.07-2.12 s
after. This writes what that made — `bestiary.people_block`, the one maker — to
content/npc-builds/people-sheets.json, each sheet stamped with the build it was made from
(`bestiary.build_stamp`). At start a sheet is used only when its stamp is the build's own;
any other build is made live, so a file left stale is slow, never wrong, and
tests/test_people_sheets.py fails until this is run again.

Re-run after changing people.json or anything that changes what a build becomes (the
engine's arithmetic, a class, a race, the gear tables). `tools/build_npc_roster.py` runs it
after writing the roster.

    python tools/build_people_sheets.py
    python tools/build_people_sheets.py --check     # exit 1 if the file is stale
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "pathfindergm.settings")

import django  # noqa: E402

django.setup()

from rules import bestiary  # noqa: E402

BUILDS = ROOT / "content" / "npc-builds"


def sheets() -> dict[str, dict]:
    """{build id: {"stamp", "block"}} for every shipped build, made live."""
    out: dict[str, dict] = {}
    for path in sorted(BUILDS.glob("*.json")):
        if path.name == bestiary.SHEETS_FILE:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        for doc in (data.get("builds") if isinstance(data, dict) else None) or []:
            block = bestiary.people_block(doc)
            out[block["id"]] = {"stamp": bestiary.build_stamp(doc), "block": block}
    return out


def text(made: dict[str, dict]) -> str:
    return json.dumps({
        "note": ("Generated by tools/build_people_sheets.py from people.json: each build as "
                 "the engine makes it (bestiary.people_block), stamped with the build. Never "
                 "edit by hand; re-run the tool."),
        "sheets": dict(sorted(made.items()))}, indent=1, ensure_ascii=False) + "\n"


def main(check: bool = False) -> int:
    out = BUILDS / bestiary.SHEETS_FILE
    made = sheets()
    want = text(made)
    if check:
        have = out.read_text(encoding="utf-8") if out.is_file() else ""
        if have != want:
            print(f"stale: {out.relative_to(ROOT)} — run tools/build_people_sheets.py")
            return 1
        print("fresh")
        return 0
    out.write_text(want, encoding="utf-8")
    print(f"wrote {len(made)} sheets to {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(check="--check" in sys.argv[1:]))
