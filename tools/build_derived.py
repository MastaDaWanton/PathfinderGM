"""Templated creatures the game ships, declared by base and template (rules/templates.py).

Two lists, each with its reason:

- **Summonable creatures.** CRB Table 10-1, "Summon Monster" (p. 351, read 2026-10-28): every
  entry marked * "is summoned with the celestial template if you are good, or the fiendish
  template if you are evil" — 61 bases across spell levels 1-7, of which 58 are in the
  shipped Bestiaries (the giant soldier and drone ants and the giant lizard are not).
  Each is declared both ways.
- **The common raised dead.** Zombies and skeletons of the creatures a GM most often raises
  — the everyday beasts and humanoids of the Bestiary — replacing the adventures' own
  printed zombie and skeleton rows, which the measurement in tests/test_templates.py found
  breaking the template's rules as often as following them.

A declaration the rules refuse (a skeleton of a vermin, a young dragon) is refused here
too, and this script stops with the reason rather than write it.

    python tools/build_derived.py      # writes content/bestiary/derived.json
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "pathfindergm.settings")

import django  # noqa: E402

django.setup()

from rules import bestiary, templates  # noqa: E402

# CRB Table 10-1's starred entries, spell levels 1-7, by the Bestiary block's name.
SUMMONED = [
    "dire rat", "dog", "dolphin", "eagle", "fire beetle", "poison frog", "pony", "viper",
    "giant ant", "giant centipede", "giant frog", "giant spider", "goblin dog", "horse",
    "hyena", "octopus", "squid", "wolf",
    "gorilla", "aurochs", "boar", "cheetah", "constrictor snake", "crocodile", "dire bat",
    "electric eel", "leopard", "shark", "wolverine",
    "bison", "deinonychus", "dire ape", "dire boar", "dire wolf", "giant scorpion",
    "giant wasp", "grizzly bear", "lion", "pteranodon", "rhinoceros",
    "ankylosaurus", "orca", "dire lion", "giant moray eel", "woolly rhinoceros",
    "dire bear", "dire tiger", "elasmosaurus", "elephant", "giant octopus", "triceratops",
    "brachiosaurus", "dire crocodile", "dire shark", "giant squid", "mastodon", "roc",
    "tyrannosaurus",
]

RAISED = ["wolf", "dire wolf", "dog", "horse", "grizzly bear", "boar", "ogre", "troll",
          "orc", "goblin", "hobgoblin", "gnoll", "bugbear", "lizardfolk", "shark",
          "crocodile", "owlbear", "minotaur", "hill giant", "worg", "elephant", "lion",
          "hyena", "dire rat"]


def _id(name: str) -> str:
    """The shipped block a Bestiary name means, by its words in either order."""
    want = sorted(name.lower().split())
    for bid, block in bestiary.imported().items():
        if sorted(str(block.get("name") or "").lower().split()) == want \
                and str(block.get("source") or "").startswith("Bestiary"):
            return bid
    raise SystemExit(f"no Bestiary block named {name!r}")


def main() -> None:
    decls = []
    for name in SUMMONED:
        decls += [{"base": _id(name), "templates": [t], "why": "CRB Table 10-1 (summon monster)"}
                  for t in ("celestial", "fiendish")]
    for name in RAISED:
        decls += [{"base": _id(name), "templates": [t], "why": "a commonly raised dead"}
                  for t in ("zombie", "skeleton")]
    for d in decls:
        block, why = templates.apply_all(d["base"], d["templates"])
        if block is None:
            raise SystemExit(f"{d}: {why}")
    path = ROOT / "content" / "bestiary" / "derived.json"
    path.write_text(json.dumps({"note": "Templated creatures, built at load by rules/templates.py; "
                                        "generated by tools/build_derived.py.",
                                "derived": decls}, indent=1, ensure_ascii=False) + "\n",
                    encoding="utf-8")
    print(f"wrote {len(decls)} declarations")


if __name__ == "__main__":
    main()
