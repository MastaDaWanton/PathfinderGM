def _render(spec: dict) -> str:
    try:
        line = effectspec.render(spec)
    except Exception:
        line = spec.get("type", "?")
    return f"**{line}**" if materials.is_negative(spec) else line


def _grant_words(grants: dict | None) -> str:
    if not grants:
        return "nothing (mote supply)"
    if "enhancement" in grants:
        return f"+{grants['enhancement']} enhancement"
    if grants.get("property"):
        bits = [grants["property"]]
        if grants.get("choice"):
            bits.append(", ".join(f"{v}" for v in grants["choice"].values()))
        if grants.get("bonus"):
            bits.append(f"+{grants['bonus']}")
        return " ".join(bits)
    return f"power {grants.get('power')}"


def _old(path: str):
    try:
        raw = subprocess.run(["git", "show", f"{BEFORE}:{path}"], cwd=ROOT,
                             capture_output=True, check=True).stdout
        return json.loads(raw.decode("utf-8"))
    except Exception:
        return None


def build() -> str:
    ench = json.loads((ROOT / "content/materials/enchanter-materials.json")
                      .read_text(encoding="utf-8"))
    items = json.loads((ROOT / "content/materials/magic-items.json")
                       .read_text(encoding="utf-8"))
    fams = ench["families"]
    rows = [r for r in ench["materials"] if r.get("kind") == "essence"]
    old_e = _old("content/materials/enchanter-materials.json")
    old_tier = {r["id"]: r.get("tier") for r in (old_e or {}).get("materials", [])}
    out = [HEAD, OPEN]

    out.append("## The phases of the day\n")
    out.append("The owner's ruling (round 4 point 10, round 5): phases of the day from "
               "`rules/sky.py`, never a planet. Each family favours one; inside it the "
               "Bind windows are 1.5 times wider (your round 4 number). Counts are "
               "essences on the shelf.\n")
    by_phase = {p: [] for p in sky.PHASES}
    for name, fam in fams.items():
        by_phase.setdefault(fam["phase"], []).append(name)
    out.append("| Phase | Families |\n|---|---|")
    for p in sky.PHASES:
        names = sorted(by_phase.get(p, []))
        out.append(f"| {p} | {', '.join(names) or '(none)'} |")
    out.append("")
    out.append("| Family | Phase | Why | Affinity | Working | Essences |\n"
               "|---|---|---|---|---|---|")
    for name in sorted(fams, key=lambda n: (sky.PHASES.index(fams[n]["phase"]), n)):
        fam = fams[name]
        n = sum(1 for r in rows if r.get("family") == name)
        why = fam["why"].replace("|", "/")
        out.append(f"| {name} | {fam['phase']} | {why} | {', '.join(fam['affinity'])} | "
                   f"{', '.join(fam['working']) or '-'} | {n} |")
    out.append("")

    out.append("## The essences\n")
    out.append(f"{len(rows)} essences ({sum(1 for r in rows if r['id'] not in old_tier)} "
               f"new). Price is motes × 100 for a bought essence; a found one has none. "
               f"\"Was\" is the tier before the pass, where it moved.\n")
    out.append("| Essence | Tier | Was | Family | Polarity | Grants | Motes | Price | "
               "House top-ups | How |\n|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(rows, key=lambda r: (materials.TIERS.index(r["tier"]), r["family"],
                                         r["id"])):
        was = old_tier.get(r["id"])
        was = "new" if was is None else ("" if was == r["tier"] else was)
        price = f"{r['price_gp']:,}" if r.get("price_gp") else "-"
        house = "; ".join(_render(h) for h in r.get("house") or [])
        out.append(f"| {r['name']} | {r['tier']} | {was} | {r['family']} | "
                   f"{r['polarity']} | {_grant_words(r.get('grants'))} | {r['motes']} | "
                   f"{price} | {house} | {r.get('obtain')} |")
    out.append("")

    wond = [r for r in items["materials"] if r.get("kind") == "wondrous"]
    old_i = _old("content/materials/magic-items.json")
    out.append("## The magic items re-tiered by price\n")
    if old_i is None:
        out.append("(git could not read the catalogue before the pass; run from a "
                   "checkout.)\n")
    else:
        before = {r["id"]: r for r in old_i["materials"]}
        moved = [(r, before[r["id"]]) for r in wond
                 if r["id"] in before and before[r["id"]].get("tier") != r.get("tier")]
        out.append(f"{len(moved)} of {len(wond)} wondrous rows moved (the pricing lane "
                   f"counted 35 before this pass; the Headband of Ponderous Recollection "
                   f"is the 36th, because its book price is 5,100 gp, not 500). Checked on "
                   f"load: `materials.magic_item_tier_problems`.\n")
        out.append("| Item | Price | Was | Now |\n|---|---|---|---|")
        for r, o in sorted(moved, key=lambda x: float(x[0]["price_gp"])):
            out.append(f"| {r['name']} | {float(r['price_gp']):,.0f} | {o.get('tier')} | "
                       f"{r['tier']} |")
        out.append("")

        out.append("## Book fixes in the catalogue\n")
        out.append("Each read from the AoN page in the row's `source` (fetched "
                   "2026-10-05). The old caster levels folded the creator's level "
                   "requirement into the item's caster level (the plan's Ring of "
                   "Protection +4 at CL 20 where the book prints CL 5 and a creator level "
                   "of 12); they are two fields now.\n")
        out.append("| Item | What changed |\n|---|---|")
        for r in wond:
            o = before.get(r["id"])
            if not o or r.get("retired"):
                continue
            bits = []
            if o.get("name") != r.get("name"):
                bits.append(f"name {o.get('name')} → {r.get('name')}")
            if o.get("price_gp") != r.get("price_gp"):
                bits.append(f"price {o.get('price_gp'):,} → {r.get('price_gp'):,} gp")
            if o.get("caster_level") != r.get("caster_level"):
                bits.append(f"CL {o.get('caster_level')} → {r.get('caster_level')}")
            if r.get("creator_level"):
                bits.append(f"creator level {r['creator_level']}")
            old_sp = [o["spell"]] if o.get("spell") else []
            new_sp = [s for g in r.get("spells") or [] for s in g]
            if old_sp != new_sp:
                bits.append(f"spells {', '.join(old_sp) or 'none'} → "
                            f"{', '.join(new_sp) or 'none'}")
            if r.get("creator"):
                bits.append("creator: " + "; ".join(r["creator"]))
            if o.get("slot") != r.get("vessel") and r.get("vessel") != "slotless":
                bits.append(f"slot {o.get('slot')} → {r.get('vessel')}")
            if bits:
                out.append(f"| {r['name']} | {'; '.join(bits)} |")
        out.append("")

    out.append("## Retired: not in the book\n")
    out.append("Not on the Core Rulebook's rings, wondrous items or rods pages, Ultimate "
               "Equipment's slot pages or the Advanced Player's Guide's (all fetched "
               "2026-10-05), nor found by a web search. Kept loadable for old saves; "
               "never offered as recipes.\n")
    out.append("| Id | Name | Price | Why |\n|---|---|---|---|")
    for r in wond:
        if r.get("retired"):
            out.append(f"| {r['id']} | {r['name']} | {float(r['price_gp']):,.0f} | "
                       f"{r.get('why_retired', '')} |")
    out.append("")

    out.append("## What the recipes still cannot run\n")
    waiting: dict[str, int] = {}
    with_not_yet = 0
    live = [r for r in wond if not r.get("retired")]
    for r in live:
        for spec in r.get("book") or []:
            if not effectspec.executable(spec):
                waiting[spec.get("type")] = waiting.get(spec.get("type"), 0) + 1
        if r.get("not_yet"):
            with_not_yet += 1
    out.append(f"{len(live)} recipes, none narrative. Book documents of a type the engine "
               f"does not run yet, by type: "
               + ", ".join(f"{t} {n}" for t, n in sorted(waiting.items()))
               + f". {with_not_yet} recipes say in `not_yet` what of the book they leave "
                 f"out.\n")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/enchanting-review.md is stale: run python tools/enchant_review.py")
            return 1
        print("docs/enchanting-review.md is current.")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
