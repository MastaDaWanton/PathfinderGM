from rules import effectspec, materials, sky  # noqa: E402

OUT = ROOT / "docs" / "enchanting-review.md"
BEFORE = "511cee9"   # build/enchanting at the start of lane D (2026-10-05)

HEAD = """# Enchanting: the data pass, for review

Generated by `tools/enchant_review.py` from `content/materials/enchanter-materials.json` and
`content/materials/magic-items.json`; do not edit by hand (run the tool after changing the
data; `--check` says whether this page is stale). The numbers are written by
`tools/enchant_data_pass.py`, which validates every row before it writes.

How to read it:

- **Book** numbers (every price, caster level, creator level and every amount in a
  recipe's book effects, and what a granted property does) are the printed PF1e ones, read
  by hand from the AoN page each recipe cites. They are listed so you can see the whole
  item, not offered for tuning.
- **House** numbers are this pass's drafts for your judgment: each essence's top-ups, the
  motes of an essence that grants nothing, which family sits in which phase of the day,
  and each family's affinity materials. Top-ups stay inside the ceilings you accepted
  (common and uncommon ±1, rare and exotic ±2, legendary ±3) and are scaled by binding
  quality; drawbacks are in **bold**.
- **Motes**: 1 mote = 100 gp of the book's making cost (your round 4 ruling). A bought
  essence carries exactly the making cost of what it grants on the cheapest item that can
  carry it, so buying the essences for an item costs the book's price. Worked: a +1
  flaming longsword is 8,000 gp market, 4,000 to make, 40 motes = Arcane Essence I (10,
  grants +1) + Flaming Essence (30, grants flaming). Found and harvested essences may carry
  more motes than their grant (a trophy is richer than a shop phial) and are never sold.
- **Tier** is a price band, the one you set for magic items: under 1,000 gp common, under
  5,000 uncommon, under 20,000 rare, under 50,000 exotic, then legendary. An essence is
  banded on the market value its motes carry (motes × 200 gp), which the price rule forces:
  a rarer essence may never cost less than a commoner one, and an essence costs motes ×
  100. The first draft kept lane A's property tiers and failed it (ghost touch exotic at
  3,000 gp under arcane essence III rare at 9,000).
"""

