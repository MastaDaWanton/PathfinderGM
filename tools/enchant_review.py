"""Writes docs/enchanting-review.md: the enchanting data pass laid out for the owner.

Generated from the data, so the page cannot drift from it:

    python tools/enchant_review.py           # write the page
    python tools/enchant_review.py --check   # exit 1 if the page is stale

The "book fixes" and "re-tier" tables compare the catalogue with the version before the
pass (`BEFORE`, the commit lane D branched from), read through git; without git they are
left out and say so.
"""
